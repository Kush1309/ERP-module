// Extra CRUD/edge coverage run after run2's flows
const { req, check, summary } = require('./lib');
module.exports = async function extra(S) {
  console.log('== EXTRA CRUD');
  let r = await req('DELETE', `/subjects/${S.sub._id}`, { token: S.admin });
  check('cannot delete subject in use 409', r.status === 409, r);
  r = await req('POST', '/subjects', { token: S.admin, body: { name: 'NoCode' } });
  check('subject missing code 400 (no crash)', r.status === 400, r);
  r = await req('DELETE', `/exams/${S.exam._id}`, { token: S.admin });
  check('cannot delete exam with results 409', r.status === 409, r);
  r = await req('POST', '/exams', { token: S.admin, body: { name: 'Temp', type: 'UNIT_TEST', academicSession: '2026-27', class: '8', startDate: '2026-12-01', endDate: '2026-12-02' } });
  r = await req('DELETE', `/exams/${r.body?.data?.exam?._id}`, { token: S.admin });
  check('delete empty exam', r.status === 200, r);
  r = await req('PUT', `/notices/${S.noticeAll._id}`, { token: S.admin, body: { title: 'All notice (edited)' } });
  check('update notice', r.status === 200, r);
  r = await req('PATCH', `/notices/${S.noticeAll._id}/archive`, { token: S.admin });
  check('archive notice', r.status === 200, r);
  r = await req('GET', '/student/notices', { token: S.stu1Tok });
  check('archived notice hidden from student', !JSON.stringify(r.body).includes('All notice (edited)'), r);
  r = await req('DELETE', `/notices/${S.notice9._id}`, { token: S.admin });
  check('delete notice', r.status === 200 || r.status === 204, r);
  r = await req('PUT', `/timetable/${S.tt._id}`, { token: S.admin, body: { room: 'R9' } });
  check('update timetable', r.status === 200, r);
  r = await req('GET', '/events', { token: S.admin });
  r = await req('POST', '/events', { token: S.admin, body: { title: 'Sports Day', eventDate: '2026-12-10', eventType: 'SPORTS', targetAudience: 'ALL', status: 'PUBLISHED' } });
  check('create event', r.status === 201, r);
  const ev = r.body?.data?.event || r.body?.data;
  r = await req('GET', '/events', { token: S.stu1Tok });
  check('student sees published event', r.status === 200 && JSON.stringify(r.body).includes('Sports Day'), r);
  r = await req('POST', '/events', { token: S.admin, body: { title: 'Staff Meeting', eventDate: '2026-12-11', eventType: 'MEETING', targetAudience: 'TEACHERS', status: 'PUBLISHED' } });
  await req('POST', '/events', { token: S.admin, body: { title: 'Draft Fair', eventDate: '2026-12-12', eventType: 'CULTURAL', targetAudience: 'ALL', status: 'DRAFT' } });
  r = await req('GET', '/events', { token: S.stu1Tok });
  check('student does not see teacher-only or draft events', !/Staff Meeting|Draft Fair/.test(JSON.stringify(r.body)), r.body);
  r = await req('GET', '/events', { token: S.t1Tok });
  check('teacher sees teacher event', JSON.stringify(r.body).includes('Staff Meeting'), r.body);
  r = await req('POST', '/events', { token: S.stu1Tok, body: { title: 'x', eventDate: '2026-12-10', eventType: 'SPORTS', targetAudience: 'ALL' } });
  check('student cannot create event', r.status === 403, r);
  r = await req('DELETE', `/events/${ev?._id}`, { token: S.admin });
  check('delete event', r.status === 200 || r.status === 204, r);
  r = await req('PATCH', `/parents/${S.parent._id}/deactivate`, { token: S.admin });
  check('deactivate parent', r.status === 200 && r.body.data.parent.user.isActive === false, r);
  r = await req('GET', '/parent/students', { token: S.parTok });
  check('deactivated parent token rejected', r.status === 403 || r.status === 401, r);
  r = await req('POST', '/auth/login', { body: { loginId: 'ADM2026000001', password: 'x' }, raw: '{bad json', headers: { 'Content-Type': 'application/json' } });
  check('malformed JSON 400', r.status === 400, r);
  r = await req('GET', '/students?status[$ne]=X', { token: S.admin });
  check('operator in query stripped', r.status === 200, r);
};
