  check('vacate bed', r.status === 200 && r.body.data.status === 'VACATED', r);

  r = await req('POST', '/inventory/items', { token: S.admin, body: { name: 'Whiteboard marker', category: 'Stationery', sku: 'MRK-' + uniq, quantity: 10, reorderLevel: 5 } });
