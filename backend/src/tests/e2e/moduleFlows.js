  check('stock ledger', r.body.data.transactions.length === 3 && r.body.data.transactions[0].balanceAfter === 24, r.body.data);
  r = await req('DELETE', `/inventory/items/${item._id}`, { token: S.admin });
  check('cannot delete item with history', r.status === 409, r);
  r = await req('GET', '/inventory/items', { token: S.libTok });
  check('librarian cannot access inventory', r.status === 403, r);

  console.log('== STUDENT LIFECYCLE');
