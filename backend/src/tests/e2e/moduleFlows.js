  check('allocate bed', r.status === 201, r);
  const alloc = r.body?.data;
  r = await req('POST', '/hostel/allocations', { token: S.admin, body: { room: room._id, student: S.stu2._id } });
  check('room full rejected', r.status === 409, r);
  r = await req('PUT', `/hostel/rooms/${room._id}`, { token: S.admin, body: { capacity: 2 } });
  r = await req('POST', '/hostel/allocations', { token: S.admin, body: { room: room._id, student: S.stu1._id } });
  check('student cannot hold two beds', r.status === 409, r);
  r = await req('GET', '/hostel/my', { token: S.stu1Tok });
  check('student sees own hostel room', r.status === 200 && r.body.data[0]?.room?.roomNumber === '101', r);
  r = await req('GET', '/hostel/report', { token: S.admin });
